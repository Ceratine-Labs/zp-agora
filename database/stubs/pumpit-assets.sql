   [PumpIT] asset masters — LOCAL STUB ONLY.

   The four legacy asset masters the Assets module (slot 17) reads through
   agora.vw_AssetGroup, vw_AssetType, vw_AssetOwner and vw_AssetMovementType.
   Without them those views will not CREATE locally, because three-part names
   are resolved when a view is created.

   Types copied from the live instance on 27 Sep 2026 (column for column; the
   customer keeps a primary key on each, which this stub leaves off like the
   other stub files). MIST_EOD is carried because the live tables have it and
   nothing reads it.

   UNLIKE THE OTHER STUB FILES THIS ONE ALSO CARRIES THE ROWS. They are
   reference data, not the estate: 21 groups, 431 types, 31 owners and 5
   movement types, all copied from live on 27 Sep 2026, so a local register
   offers the groups a site actually uses. Each insert skips a row
   that is already there, so the file can be run again. Tests do not rely on
   these rows: they add their own TEST- group and remove it afterwards.

   Agora never writes these tables, here or on live (Ryan, 27 Sep 2026, PM
   decision 01a0e309: the register is Agora-owned; the legacy masters are read
   only). The legacy ASSET_AssetRegister / AssetMovement / AssetRepair tables
   hold 8 / 1 / 3 pilot rows from 4 Jun 2026 and are deliberately not stubbed:
   nothing in Agora reads them.

   This file is NEVER run against the customer's instance.

   Run by scripts/local-sql.sh up. It depends on no other stub file, so its
   place in the list does not matter. By hand:

     docker exec -i agora-sql /opt/mssql-tools18/bin/sqlcmd -S localhost -U sa \
         -P "$AGORA_DB_PASSWORD" -C -b -d PumpIT -i /dev/stdin < database/stubs/pumpit-assets.sql
   ============================================================================ */

